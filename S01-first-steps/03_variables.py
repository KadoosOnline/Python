# A variable is a name that refers to a value.
# Naming rules: letters, digits and underscore only, never start with a digit,
# and the name must not be a Python keyword (if, for, class, ...).
name = 'Kadoos'      # text
age = 18             # whole number
score = 19.5         # number with a decimal part
single = True        # True or False

print(name)
print(age)
print(score)
print(single)

# A variable can be re-assigned at any time.
age = 19
print('The new age is:', age)
