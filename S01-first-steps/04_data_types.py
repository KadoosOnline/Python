# Python has four basic (scalar) data types that we use from day one.
name = 'Kadoos'      # str   -> text, always inside quotes
age = 18             # int   -> integer number
score = 19.5         # float -> decimal number
single = True        # bool  -> only True or False

print(name, age, score, single)

# Single quotes and double quotes are equivalent in Python.
city = "Rasht"
print(city)
