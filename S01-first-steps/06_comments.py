# Everything after a '#' on a line is a comment: Python ignores it.
# Comments explain WHY the code does something, not WHAT it does.

print('Hello Kadoos!')  # a comment can also sit at the end of a line

# Python has no real multi-line comment, but a triple-quoted string that is not
# assigned to anything is often used for the same purpose.
'''
These three lines are a string that nobody uses,
so in practice they behave like a multi-line comment.
'''

print('The program continues here.')
