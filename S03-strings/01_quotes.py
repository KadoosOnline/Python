# Single quotes and double quotes do exactly the same thing.
a = 'Kadoos'
b = "Kadoos"
print(a, b)

# Use one kind of quote when the text contains the other kind.
print("I'm a student")
print('He said "hello"')

# Triple quotes keep the line breaks exactly as they are written.
text = '''Hello,
This is a multi-line text.
Goodbye!'''
print(text)
