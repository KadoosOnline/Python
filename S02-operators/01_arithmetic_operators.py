# All the arithmetic operators of Python, applied to the same two numbers.
num1 = 24
num2 = 6

print('+  :', num1 + num2)    # addition        -> 30
print('-  :', num1 - num2)    # subtraction     -> 18
print('*  :', num1 * num2)    # multiplication  -> 144
print('/  :', num1 / num2)    # true division   -> 4.0  (always a float!)
print('// :', num1 // num2)   # floor division  -> 4    (whole part only)
print('%  :', num1 % num2)    # remainder       -> 0
print('** :', num1 ** num2)   # power           -> 24^6
