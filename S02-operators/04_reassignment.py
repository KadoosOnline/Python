# A variable can be updated using its own current value.
# The right-hand side is calculated first, then stored back into the name.
num1 = 24
num2 = 6

num1 = num1 + num2   # 24 + 6 = 30
print(num1)

num1 = num1 - num2   # 30 - 6 = 24
print(num1)

number = 3
result = number + 1
print(result)        # 4
